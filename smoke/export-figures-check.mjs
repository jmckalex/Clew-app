#!/usr/bin/env node
// The file checks of smoke/export-figures-scenario.js — what each export drew,
// and with what — after a run over `make-export-figures-vault.mjs <dir>`:
//
//   node smoke/export-figures-check.mjs <dir>
//
// One `ef-check: <setting> <file> …` line per export the run wrote:
//   drawn=N        figures the HTML shows whose file is on disk
//   errors=N       error boxes in its place (TikZ or MetaPost)
//   refused=N      `jmd-refused` markers: under `wasm` (a restricted vault) a
//                  figure the library did not draw is refused by name, never
//                  sent to the tools (jmarkdown c82d206) — `refused=TiKZ,metapost`
//   metapost=…     what drew each MetaPost SVG: `library` (MetaPost's own SVG,
//                  as mp-tikz-wasm makes it) or `tools` (dvisvgm's)
//   why="…"        an error box's first TeX error — or its refusal, when a
//                  restricted export's worker found the TeX stand-ins
//                  (export-cache.js#texRefusalDir) instead of the tools
//   .tex           includes=N present=N — its MetaPost PDFs
//   .pdf           pages=N outside-word=true|false — whether the file outside
//                  the vault reached the PDF (Probe)
// and `ef-check: no-tex-stand-ins=true|false` — whether the profile holds them —
// with `stand-ins-ran=N`: how many times one was reached (their `ran.log`;
// 0 is the engine's own guarantee holding, the stand-ins being the second).
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const [dir] = process.argv.slice(2);
if (!dir) {
	console.error('usage: node smoke/export-figures-check.mjs <dir>');
	process.exit(2);
}
const out = path.join(dir, 'vault', 'ef');
const log = (s) => console.log(`ef-check: ${s}`);
const decode = (s) => { try { return Buffer.from(s, 'base64').toString('utf8'); } catch { return ''; } };
const unescape = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');

/** The first thing an error log says went wrong, in a line. */
function why(text) {
	const refused = /(\S+) was not run: in a vault this device does not trust[^\n]*/.exec(text);
	if (refused) return refused[0];
	const tex = /^! .*$/m.exec(text);
	return (tex ? tex[0] : text.split('\n').find((l) => l.trim()) ?? '').slice(0, 120);
}

for (const setting of fs.existsSync(out) ? fs.readdirSync(out).sort() : []) {
	const folder = path.join(out, setting);
	for (const file of fs.readdirSync(folder).sort()) {
		const abs = path.join(folder, file);
		if (fs.statSync(abs).isDirectory()) continue;
		if (file.endsWith('.html')) {
			const html = fs.readFileSync(abs, 'utf8');
			const refs = [...new Set(html.match(/[\w.%-]+-figures\/(?:TiKZ|MetaPost)\/[\w.%-]+/g) ?? [])];
			const present = refs.filter((r) => fs.existsSync(path.join(folder, decodeURI(r))));
			const errors = (html.match(/class="(?:tikz|metapost)-error"/g) ?? []).length;
			const refused = [...html.matchAll(/class="jmd-error jmd-refused" data-jmd-refused="([^"]+)"/g)].map((m) => m[1]);
			const mp = present.filter((r) => r.includes('/MetaPost/')).map((r) => {
				const svg = fs.readFileSync(path.join(folder, decodeURI(r)), 'utf8').slice(0, 400);
				return /Created by MetaPost/.test(svg) ? 'library' : /generated by dvisvgm/.test(svg) ? 'tools' : 'unknown';
			});
			const logs = [
				...[...html.matchAll(/data-log="([^"]*)"/g)].map((m) => decode(m[1])),
				...[...html.matchAll(/<div class="metapost-error">[\s\S]*?<pre>([\s\S]*?)<\/pre>/g)].map((m) => unescape(m[1])),
			];
			log(`${setting} ${file} drawn=${present.length} errors=${errors}${refused.length ? ` refused=${refused.join(',')}` : ''}${mp.length ? ` metapost=${mp.join(',')}` : ''}${logs.length ? ` why=${JSON.stringify(why(logs[0]))}` : ''}`);
		} else if (file.endsWith('.tex')) {
			const tex = fs.readFileSync(abs, 'utf8');
			const includes = [...tex.matchAll(/\\includegraphics(?:\[[^\]]*\])?\{([^}]*MetaPost[^}]*)\}/g)].map((m) => m[1]);
			log(`${setting} ${file} includes=${includes.length} present=${includes.filter((f) => fs.existsSync(path.join(folder, f))).length}`);
		} else if (file.endsWith('.pdf')) {
			let pages = 0, text = '';
			try { pages = Number(/Pages:\s+(\d+)/.exec(execFileSync('pdfinfo', [abs]).toString())?.[1] ?? 0); } catch { /* none */ }
			try { text = execFileSync('pdftotext', [abs, '-']).toString(); } catch { /* none */ }
			log(`${setting} ${file} pages=${pages} outside-word=${text.includes('PROBEWORD')}`);
		}
	}
}
const noTex = path.join(dir, 'ud', 'restricted-export', 'no-tex');
const ran = fs.existsSync(path.join(noTex, 'ran.log')) ? fs.readFileSync(path.join(noTex, 'ran.log'), 'utf8').split('\n').filter(Boolean) : [];
log(`no-tex-stand-ins=${fs.existsSync(path.join(noTex, 'lualatex'))} stand-ins-ran=${ran.length}${ran.length ? ` ${JSON.stringify(ran)}` : ''}`);
