// Regenerate src/shared/pdf-fonts.json from the installed @embedpdf font
// packages: which files each CJK pack holds, their weights, and how big the
// pack is. That JSON is committed and shipped (2.6 KB) so the app can
// download exactly the right files without the 139 MB of fonts ever being a
// build dependency — see src/main/pdf-fonts.js.
//
// Run after bumping the EmbedPDF version:  node scripts/gen-pdf-fonts.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// charset ids are PdfAnnotation FontCharset values from @embedpdf/models.
const PACKS = [
	{ id: 'jp', pkg: '@embedpdf/fonts-jp', charset: 128, label: 'Japanese' },
	{ id: 'kr', pkg: '@embedpdf/fonts-kr', charset: 129, label: 'Korean' },
	{ id: 'sc', pkg: '@embedpdf/fonts-sc', charset: 134, label: 'Chinese (Simplified)' },
	{ id: 'tc', pkg: '@embedpdf/fonts-tc', charset: 136, label: 'Chinese (Traditional)' },
];

const out = { note: 'Generated by scripts/gen-pdf-fonts.js — do not hand-edit.', packs: [] };
for (const pack of PACKS) {
	const dir = path.join(root, 'node_modules', pack.pkg);
	const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
	const src = fs.readFileSync(path.join(dir, 'dist', 'index.js'), 'utf8');
	const fonts = [...src.matchAll(/file:\s*"([^"]+)",\s*weight:\s*(\d+)(,\s*italic:\s*(true|false))?/g)]
		.map((m) => ({ file: m[1], weight: Number(m[2]), ...(m[4] === 'true' ? { italic: true } : {}) }));
	if (fonts.length === 0) throw new Error(`No fonts parsed from ${pack.pkg}`);
	const bytes = fonts.reduce((sum, f) => sum + fs.statSync(path.join(dir, 'fonts', f.file)).size, 0);
	out.packs.push({ ...pack, version: meta.version, bytes, fonts });
}

fs.writeFileSync(path.join(root, 'src/shared/pdf-fonts.json'), JSON.stringify(out, null, '\t') + '\n');
const total = out.packs.reduce((sum, p) => sum + p.bytes, 0);
console.log(`pdf-fonts: ${out.packs.length} packs, `
	+ `${out.packs.reduce((n, p) => n + p.fonts.length, 0)} files, ${(total / 1048576).toFixed(0)} MB`);
